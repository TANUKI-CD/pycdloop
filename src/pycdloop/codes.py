"""Linear codes in loop algebras.

A code in a loop algebra ``F[L]`` is a subspace, read as a linear code of
length ``len(L)`` through the loop-basis coefficients, so that the weight of
an element is its Hamming weight. The codes of interest are the one-sided
ideals: subspaces closed under multiplication by every element on one side,
or equivalently under translation by every loop element on that side.

Matrices here have one row for each codeword and one column for each loop
element, in the iteration order of the loop, with a trailing polynomial axis
over an extension field.

Examples
--------
>>> import pycdloop as cdl
>>> from pycdloop import codes
>>> Q = cdl.CDLoop(2)
>>> A = cdl.LoopAlgebra(Q, char=3)
>>> x = A.basis(Q.basis(0)) + A.basis(Q.basis(1))
>>> codes.generator_matrix(x).shape
(6, 8)
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any

import numpy as np

from . import linalg
from ._element import Element
from ._field import _coefficient_field
from ._validation import DIFFERENT_ALGEBRA_MESSAGE, _choice

__all__ = ["generator_matrix", "to_gap", "to_sage", "translate_matrix"]

_SIDES = ("left", "right")


def _translates(algebra: Any, rows: np.ndarray, side: str) -> np.ndarray:
    """Return every translate of every row, as rows of one matrix."""

    # Translating by a loop element permutes the basis: the coefficient of
    # [y] in x moves to [g y] under left translation by g and to [y g] under
    # right translation
    loop = algebra.loop
    positions = np.arange(loop.order, dtype=np.int64)
    if side == "left":
        targets = loop._multiply_positions(positions[:, None], positions[None, :])
    else:
        targets = loop._multiply_positions(positions[None, :], positions[:, None])
    count = rows.shape[0]
    shape = (count, loop.order, loop.order) + algebra._field.shape
    moved = np.empty(shape, dtype=rows.dtype)
    moved[:, positions[:, None], targets] = rows[:, None]
    return moved.reshape((count * loop.order, loop.order) + algebra._field.shape)


def _flatten(element: Any) -> np.ndarray:
    """Return the loop-basis coefficients of one element as a row."""

    algebra = element._algebra
    return np.asarray(element.coefficients).reshape(
        (1, algebra.dimension) + algebra._field.shape
    )


def translate_matrix(x: Any, *, side: str = "left") -> np.ndarray:
    """Return the matrix whose rows are the translates of one element.

    Parameters
    ----------
    x : Element
        The element.
    side : str, optional
        ``"left"`` for the rows ``[g] x`` and ``"right"`` for ``x [g]``,
        with ``g`` running over the loop in iteration order.

    Returns
    -------
    numpy.ndarray
        A matrix of shape ``(dimension, dimension)``, with the polynomial
        axis of an extension field appended.
    """

    if not isinstance(x, Element):
        raise TypeError("x must be one element of a loop algebra")
    return _translates(x._algebra, _flatten(x), _choice(side, "side", _SIDES))


def generator_matrix(
    elements: Any, *, side: str = "left", closure: bool = True, tol: Any = None
) -> np.ndarray:
    """Return a generator matrix of the code generated by some elements.

    Parameters
    ----------
    elements : Element or iterable of Element
        The generators, all from one loop algebra.
    side : str, optional
        ``"left"`` for the left ideal and ``"right"`` for the right ideal.
    closure : bool, optional
        With ``True``, the default, the result spans the one-sided ideal
        generated by the elements. Because the algebra need not be
        associative, the span of the translates of the generators need not
        be closed under translation, so translates are added until the
        dimension stops growing. With ``False`` the result spans the
        translates of the generators only.
    tol : float, optional
        The tolerance of :func:`pycdloop.linalg.row_reduce` over R and C.

    Returns
    -------
    numpy.ndarray
        A matrix in reduced row echelon form whose rows are a basis of the
        code, of shape ``(k, dimension)`` with the polynomial axis of an
        extension field appended.
    """

    name = _choice(side, "side", _SIDES)
    items = [elements] if isinstance(elements, Element) else list(_checked(elements))
    if not items:
        raise ValueError("at least one generator is required")
    algebra = items[0]._algebra
    for item in items:
        if item._algebra is not algebra:
            raise ValueError(DIFFERENT_ALGEBRA_MESSAGE)
    rows = np.concatenate([_flatten(item) for item in items])
    rank = -1
    while True:
        reduced, pivots = linalg.row_reduce(
            _translates(algebra, rows, name), field=algebra.field, tol=tol
        )
        rows = reduced[: len(pivots)]
        if not closure or len(pivots) == rank:
            return np.ascontiguousarray(rows)
        rank = len(pivots)


def _checked(elements: Iterable[Any]) -> Iterable[Any]:
    """Yield generators after checking that each is an element."""

    for item in elements:
        if not isinstance(item, Element):
            raise TypeError("generators must be elements of a loop algebra")
        yield item


def _entries(matrix: Any, field: Any) -> list[list[int]]:
    """Return the residues of a matrix over a prime field as nested lists."""

    if field is None or _coefficient_field(field=field).deg != 1:
        raise ValueError("export is available over prime fields only")
    values = np.asarray(matrix)
    if values.ndim != 2 or values.dtype.kind not in "iu":
        raise ValueError("the matrix must be a two-dimensional array of residues")
    rows: list[list[int]] = (values.astype(np.int64) % field.char).tolist()
    return rows


def to_gap(matrix: Any, *, field: Any) -> str:
    """Return a GAP expression for the code with the given generator matrix.

    The expression calls ``GeneratorMatCode`` of the GUAVA package. *field*
    is the field of the entries, a ``pyfastcd.FiniteField`` or a
    :class:`~pycdloop.BinaryField`, which must be a prime field.
    """

    rows = _entries(matrix, field)
    body = ",\n".join("  " + str(row).replace(" ", "") for row in rows)
    return f"GeneratorMatCode([\n{body}\n]*Z({field.char})^0, GF({field.char}));"


def to_sage(matrix: Any, *, field: Any) -> str:
    """Return a SageMath expression for the code with the given generator matrix.

    *field* is the field of the entries, a ``pyfastcd.FiniteField`` or a
    :class:`~pycdloop.BinaryField`, which must be a prime field.
    """

    rows = _entries(matrix, field)
    body = ",\n".join("  " + str(row) for row in rows)
    return f"LinearCode(matrix(GF({field.char}), [\n{body}\n]))"
