ALGORITHMS = ("auto", "split", "table")
BINARY_ALGORITHMS = ("auto", "lift", "table")

# In characteristic 2, "auto" lifts a product instead of multiplying from the
# table when the quotient order D of the loop is at least the first number
# and the work of the table product, the number of records times D^2, is at
# least the second; a second number of 0 leaves the first condition alone.
# The pairs are for F_2, which lifts to a prime field; for F_(2^k) with
# k <= 6, which takes one product over an extension field; and for larger k,
# which takes three
LIFT_THRESHOLDS = ((1 << 1, 1 << 8), (1 << 1, 0), (1 << 4, 1 << 10))

# Largest quotient order for which the tables of the table product are built,
# and largest dimension for which dense structure constants are returned
_TABLE_LIMIT = 1 << 12
_CONSTANTS_LIMIT = 1 << 8


@dataclass(frozen=True, eq=False)
class GeneratedSubalgebra:
    """The unital subalgebra generated by one element.

    In the loop algebra of a Cayley--Dickson loop, and in every loop algebra
    of characteristic 2, the powers of an element ``x`` do not depend on
    bracketing, and they span a commutative, associative subalgebra
    isomorphic to ``F[t] / (m(t))``, where ``m`` is the minimal polynomial
    of ``x``.

    Attributes
    ----------
    dimension : int
        The dimension of the subalgebra, which is the degree of ``m``.
    minimal_polynomial : numpy.ndarray
        The coefficients of ``m``, constant term first.
    spectral_values : numpy.ndarray or None
        The distinct spectral coordinates of ``x``. Each is a root of ``m``
        and gives a homomorphism from the subalgebra to the field. ``None``
        in characteristic 2, where the algebra has no spectrum.
    signed_polynomial : numpy.ndarray or None
        The minimal polynomial of the signed component of ``x``, of degree 1
        or 2. ``m`` is this polynomial times ``t - v`` for every spectral
        value ``v`` that is not a root of it. ``None`` in characteristic 2.

    Notes
    -----
    In characteristic 2, ``m`` is ``(t - a)**j`` with ``a`` the augmentation
    of ``x`` and ``j`` between 1 and 4, so the subalgebra is a local ring of
    dimension at most 4.
    """

    dimension: int
    minimal_polynomial: np.ndarray
    spectral_values: np.ndarray | None
    signed_polynomial: np.ndarray | None


@final
class LoopAlgebra:
    """The loop algebra ``F[L]`` of a loop ``L`` over a coefficient field ``F``.

    The algebra is the vector space with one basis element ``[x]`` for each
    element ``x`` of the loop, with the product ``[x][y] = [xy]`` extended
    bilinearly.

    Parameters
    ----------
    loop : CDLoop or CentralProduct
        The loop.
    char, deg, field
        Selectors of the coefficient field, with the meaning they have in
        pyfastcd. Omitted, the coefficients are real ``float64`` values;
        ``char=0, deg=2`` selects complex coefficients; ``char=p, deg=d``
        selects the finite field with ``p**d`` elements, for an odd prime
        ``p`` or for ``p = 2``; and ``field=F`` selects a
        ``pyfastcd.FiniteField`` or a :class:`BinaryField`.

    Attributes
    ----------
    loop
        The loop.
    dimension : int
        The dimension of the algebra, equal to ``loop.order``.
    char, deg : int
        The characteristic and degree of the coefficient field.
    field : pyfastcd.FiniteField, BinaryField or None
        The finite coefficient field; ``None`` over R and C.
    dtype : numpy.dtype
        The coefficient storage type: ``float64``, ``complex128`` or
        ``uint32``.
    coefficient_shape : tuple[int, ...]
        The shape of the coefficients of one element:
        ``(2, loop.quotient_order)``, followed by ``deg`` over an extension
        field. Row 0 holds the coefficients of ``[e_t]`` and row 1 those of
        ``[-e_t]``.
    cd_algebra : pyfastcd.Algebra or None
        The Cayley--Dickson algebra that holds the signed components, for a
        Cayley--Dickson loop; ``None`` for a central product and in
        characteristic 2.

    Notes
    -----
    Algebras are immutable and cached by loop and coefficient field. Calling
    an algebra creates an :class:`Element`:

    - ``A(r)`` for a field scalar ``r`` is ``r`` times the identity;
    - ``A(x)`` for an element of ``A`` is that element;
    - ``A(values)`` reads exactly ``coefficient_shape`` coefficients.

    A loop element is not converted implicitly; use :meth:`basis`.

    Over R, C and finite fields of odd characteristic the algebra is the
    direct sum of a group algebra and the algebra of signed components, and
    products are evaluated through that decomposition. In characteristic 2
    there is no such decomposition: the methods that expose it raise
    ``TypeError``, and products are evaluated from the multiplication table
    or by lifting coefficients to a large prime field, or to an extension
    of it when the coefficient field is not F_2.

    Examples
    --------
    >>> import pycdloop as cdl
    >>> Q = cdl.CDLoop(3)
    >>> A = cdl.LoopAlgebra(Q)
    >>> x = A.basis(Q.basis(1)) + A.basis(Q.basis(2))
    >>> (x * x).terms()
    {e_3: 1.0, -e_0: 2.0, -e_3: 1.0}
    >>> F = cdl.LoopAlgebra(Q, char=13)
    >>> F.dtype
    dtype('uint32')
    >>> B = cdl.LoopAlgebra(Q, char=2)
    >>> y = B.basis(Q.basis(1)) + B.basis(Q.basis(2))
    >>> y * y == B.basis(Q.basis(3)) + B.basis(-Q.basis(3))
    True
    """

    __slots__ = (
        "loop",
        "dimension",
        "coefficient_shape",
        "_field",
        "_signed",
        "_size",
        "_lazy",
        "__weakref__",
    )

    loop: Any
    dimension: int
    coefficient_shape: tuple[int, ...]
    _field: _CoefficientField
    _signed: Any
    _size: int
    _lazy: dict[str, Any]
    _cache: dict[tuple[Any, _CoefficientField], LoopAlgebra] = {}

    def __new__(
        cls, loop: Any, *, char: Any = 0, deg: Any = 1, field: Any = None
    ) -> LoopAlgebra:
        """Validate the loop and selectors and retrieve the cached algebra."""

        parent = _loop_from(loop)
        domain = _coefficient_field(char=char, deg=deg, field=field)
        key = (parent, domain)
        if key not in cls._cache:
            with CACHE_LOCK:
                if key not in cls._cache:
                    cls._cache[key] = cls._build(parent, domain)
        return cls._cache[key]

    @classmethod
    def _build(cls, parent: Any, domain: _CoefficientField) -> LoopAlgebra:
        """Create the algebra of a loop over a field, which the caller caches."""

        self = object.__new__(cls)
        store = object.__setattr__
        store(self, "loop", parent)
        store(self, "dimension", parent.order)
        store(self, "coefficient_shape", (2, parent.quotient_order) + domain.shape)
        store(self, "_field", domain)
        # In characteristic 2 the algebra has no signed component
        signed = None if domain.binary else _signed_algebra(parent.levels, domain)
        store(self, "_signed", signed)
        store(self, "_size", parent.quotient_order)
        store(self, "_lazy", {})
        return self

    def __init_subclass__(cls, **kwargs: Any) -> None:
        """Reject subclasses so cached identity remains unambiguous."""

        raise TypeError("LoopAlgebra cannot be subclassed")

    def __setattr__(self, name: str, value: Any) -> None:
        """Reject mutation of a cached algebra."""

        raise AttributeError("LoopAlgebra objects are immutable")

    def __delattr__(self, name: str) -> None:
        """Reject deletion of immutable state."""

        raise AttributeError("LoopAlgebra objects are immutable")

    def __reduce__(self) -> tuple[Any, ...]:
        """Pickle the loop and the coefficient field."""

        return (_rebuild_algebra, (self.loop, self.char, self.deg, self.field))

    def __repr__(self) -> str:
        """Return the loop and the characteristic and degree of the field.

        The polynomial that presents a finite field is not shown.
        """

        if self.field is not None:
            return f"LoopAlgebra({self.loop!r}, char={self.char}, deg={self.deg})"
        if self.deg == 2:
            return f"LoopAlgebra({self.loop!r}, char=0, deg=2)"
        return f"LoopAlgebra({self.loop!r})"

    # Properties

    @property
    def char(self) -> int:
        """The characteristic of the coefficient field."""

        return self._field.char

    @property
    def deg(self) -> int:
        """The degree of the coefficient field."""

        return self._field.deg

    @property
    def field(self) -> Any:
        """The finite coefficient field; ``None`` over R and C.

        A ``pyfastcd.FiniteField`` in odd characteristic and a
        :class:`BinaryField` in characteristic 2.
        """

        return self._field.field

    @property
    def dtype(self) -> np.dtype[Any]:
        """The coefficient storage type."""

        return self._field.dtype

    @property
    def cd_algebra(self) -> Any:
        """The pyfastcd algebra of the signed components, or ``None``."""

        return None if self._signed is None else self._signed.cd

    @property
    def _is_cd(self) -> bool:
        """Whether the loop is a single Cayley--Dickson loop."""

        return isinstance(self.loop, CDLoop)

    @property
    def _has_powers(self) -> bool:
        """Whether the powers of an element do not depend on bracketing.

        They do not for a Cayley--Dickson loop, and for every loop in
        characteristic 2, where the square of an element is central.
        """

        return self._is_cd or self._field.binary

    @property
    def _lift(self) -> _Lift:
        """The lifting data of an algebra of characteristic 2."""

        lift: _Lift = self._memo("lift", lambda: _Lift(self, LoopAlgebra))
        return lift

    def _require_split(self, name: str) -> None:
        """Raise for an operation that needs the decomposition of the algebra."""

        if self._field.binary:
            raise TypeError(BINARY_MESSAGE.format(name=name))

    @property
    def algorithms(self) -> tuple[str, ...]:
        """The accepted values of ``algorithm`` in :meth:`multiply`."""

        return BINARY_ALGORITHMS if self._field.binary else ALGORITHMS

    def _binary_choice(self, records: int | None) -> str:
        """Return the algorithm that ``"auto"`` selects in characteristic 2.

        *records* is the number of products, or ``None`` for a batch large
        enough that only the size of the loop matters.
        """

        # Both algorithms are exact, so the choice can follow the batch size
        # without changing any result
        degree = self._field.deg
        kind = 0 if degree == 1 else 1 if degree <= _LIMB_BITS else 2
        order, work = LIFT_THRESHOLDS[kind]
        size = self._size
        if size < order:
            return "table"
        if records is not None and records * size * size < work:
            return "table"
        return "lift"

    @property
    def default_algorithm(self) -> str:
        """The algorithm that ``"auto"`` selects for a single product."""

        return self._binary_choice(1) if self._field.binary else "split"

    @property
    def default_batch_algorithm(self) -> str:
        """The algorithm that ``"auto"`` selects for a large batch.

        It differs from :attr:`default_algorithm` only in characteristic 2,
        where both algorithms are exact and ``"auto"`` chooses between them
        from the size of the loop and the number of products.
        """

        return self._binary_choice(None) if self._field.binary else "split"

    @property
    def signed_algorithms(self) -> tuple[str, ...]:
        """The accepted values of ``signed_algorithm`` in :meth:`multiply`.

        In characteristic 2 the names are those of the algebra to which
        products are lifted: over a large prime field for F_2, and over an
        extension of it otherwise.
        """

        if self._field.binary:
            lifted: tuple[str, ...] = self._lift.parent.signed_algorithms
            return lifted
        algorithms: tuple[str, ...] = self._signed.algorithms
        return algorithms

    @property
    def default_signed_algorithm(self) -> str:
        """The method that ``"auto"`` selects for the signed components.

        For a Cayley--Dickson loop this is the single-product choice of the
        pyfastcd algebra; batches follow its batch choice.
        """

        if self._field.binary:
            lifted: str = self._lift.parent.default_signed_algorithm
            return lifted
        if self._signed.cd is not None:
            name: str = self._signed.cd.default_algorithm
            return name
        default: str = self._signed.default_algorithm()
        return default

    # Cached tables

    def _memo(self, name: str, build: Any) -> Any:
        """Build a derived table once and keep it."""

        if name not in self._lazy:
            # Under the lock, so that threads share one table, and one of
            # everything that building it creates
            with CACHE_LOCK:
                if name not in self._lazy:
                    self._lazy[name] = build()
        return self._lazy[name]

    @property
    def _swap(self) -> np.ndarray:
        """Mark the indices whose basis elements square to -1."""

        def build() -> np.ndarray:
            """Evaluate the twist on the diagonal."""

            indices = np.arange(self._size, dtype=np.int64)
            marks: np.ndarray = self.loop._twist(indices, indices) < 0
            return marks

        result: np.ndarray = self._memo("swap", build)
        return result

    @property
    def _central(self) -> np.ndarray:
        """Mark the indices of the central elements of the loop."""

        def build() -> np.ndarray:
            """Intersect the commutant with the three nuclei."""

            member = self.loop._members("commutant")
            for side in ("left", "middle", "right"):
                member = member & self.loop._members(side)
            result: np.ndarray = member
            return result

        result: np.ndarray = self._memo("central", build)
        return result

    def _table(self) -> tuple[np.ndarray, np.ndarray]:
        """Return the partner indices and the positive signs of the table product."""

        def build() -> tuple[np.ndarray, np.ndarray]:
            """Tabulate ``p ^ k`` and ``sigma(p, p ^ k) > 0``."""

            if self._size > _TABLE_LIMIT:
                raise ValueError("the loop is too large for the table algorithm")
            indices = np.arange(self._size, dtype=np.int64)
            partner = indices[:, None] ^ indices[None, :]
            return partner, self.loop._twist(indices[:, None], partner) > 0

        result: tuple[np.ndarray, np.ndarray] = self._memo("table", build)
        return result

    # Wrapping

    def _element(self, mode: str, data: Any) -> Element:
        """Wrap raw data as an element."""

        return Element._make(self, mode, data)

    def _wrap_array(self, values: np.ndarray, *, shared: bool = False) -> ElementArray:
        """Wrap loop-basis coefficients as an array.

        *shared* marks storage that the caller also holds, which is then
        checked before every use.
        """

        return ElementArray._make(self, values, [True] if shared else None)

    def _signed_view(self, signed: np.ndarray) -> Any:
        """Return signed components as their public type."""

        if self._signed is not None and self._signed.cd is not None:
            return self._signed.cd.asarray(signed)
        return signed

    def _own(self, value: Any, name: str = "operand") -> Any:
        """Check that a value is an element or array of this algebra."""

        if not isinstance(value, (Element, ElementArray, SplitArray)):
            raise TypeError(f"{name} must be an element or array of the algebra")
        if value._algebra is not self:
            raise ValueError(DIFFERENT_ALGEBRA_MESSAGE)
        return value

    # Construction

    def __call__(self, value: Any = 0) -> Element:
        """Create an element from a scalar, an element or coefficients."""

        if isinstance(value, Element):
            if value._algebra is not self:
                raise ValueError(DIFFERENT_ALGEBRA_MESSAGE)
            return value
        if isinstance(value, LoopElement):
            raise TypeError("a loop element is not converted implicitly; use basis()")
        if self._field.is_scalar(value):
            return self.scalar(value)
        if isinstance(value, (bool, np.bool_)):
            raise TypeError("a boolean is not a scalar of a finite field")
        if isinstance(value, (set, frozenset, dict)):
            raise TypeError("coefficients must be an ordered sequence or an array")
        coefficients = self._field.coerce(value)
        if coefficients.shape != self.coefficient_shape:
            raise ValueError(
                f"an element has coefficient shape {self.coefficient_shape}, "
                f"not {coefficients.shape}"
            )
        return self._element("loop", coefficients)

    def zero(self) -> Element:
        """Return the additive identity."""

        return self._element("loop", self._field.zeros((2, self._size)))

    def one(self) -> Element:
        """Return the multiplicative identity ``[e_0]``."""

        return self.scalar(1)

    def scalar(self, r: Any) -> Element:
        """Return the field scalar ``r`` times the identity."""

        coefficients = self._field.zeros((2, self._size))
        coefficients[0, 0] = self._field.scalar(r)
        return self._element("loop", coefficients)

    def basis(self, x: Any) -> Element:
        """Return the basis element ``[x]`` of a loop element ``x``."""

        element = self.loop._own(x)
        coefficients = self._field.zeros((2, self._size))
        coefficients[0 if element.sign > 0 else 1, element.index] = self._field.scalar(
            1
        )
        return self._element("loop", coefficients)

    def from_terms(self, terms: Any) -> Element:
        """Return the combination of loop elements with the given coefficients.

        *terms* is a mapping from loop elements to field scalars, or an
        iterable of such pairs. Coefficients of a repeated loop element add.
        """

        field = self._field
        pairs: Iterable[Any] = terms.items() if isinstance(terms, Mapping) else terms
        coefficients = field.zeros((2, self._size))
        for x, value in pairs:
            element = self.loop._own(x)
            place = (0 if element.sign > 0 else 1, element.index)
            coefficients[place] = field.add(coefficients[place], field.scalar(value))
        return self._element("loop", coefficients)

    def _signed_coefficients(self, epsilon: Any) -> np.ndarray:
        """Read signed components given as a pyfastcd object or as coefficients."""

        field = self._field
        if isinstance(epsilon, (fcd.Element, fcd.ElementArray)):
            if epsilon.algebra is not self._signed.cd:
                raise ValueError("the signed component belongs to a different algebra")
            # The storage of a pyfastcd array is writable, so its
            # coefficients are read as any other coefficients are
            return field.coerce(np.asarray(epsilon.coefficients))
        values = field.coerce(epsilon)
        if self._signed.cd is None:
            # A central product also accepts one axis for each factor
            factors = self._signed.sizes + field.shape
            if values.ndim >= len(factors) and values.shape[-len(factors) :] == factors:
                lead = values.shape[: values.ndim - len(factors)]
                values = values.reshape(lead + (self._size,) + field.shape)
        return values

    def _components(self, kappa: Any, epsilon: Any) -> tuple[np.ndarray, np.ndarray]:
        """Validate a group component and a signed component."""

        field = self._field
        record = (self._size,) + field.shape
        group = field.coerce(kappa)
        signed = self._signed_coefficients(epsilon)
        for part in (group, signed):
            if (
                part.ndim < len(record)
                or part.shape[part.ndim - len(record) :] != record
            ):
                raise ValueError(
                    f"each component must have shape batch_shape + {record}"
                )
        return group, signed

    def from_components(self, kappa: Any, epsilon: Any) -> Any:
        """Return the element with the given group and signed components.

        This inverts ``x -> (x.kappa(), x.epsilon())``: the coefficients are
        ``a_t = (c_t + d_t) / 2`` and ``b_t = (c_t - d_t) / 2`` for group
        component ``c`` and signed component ``d``.

        Parameters
        ----------
        kappa : array_like
            The group component, of shape ``(D,)`` with ``D`` the quotient
            order of the loop, followed by the polynomial axis of an
            extension field.
        epsilon
            The signed component: a pyfastcd ``Element`` or
            ``ElementArray`` of :attr:`cd_algebra`, or coefficients of the
            same shape as *kappa*. For a central product the coefficients
            may instead have one axis for each factor.

        Returns
        -------
        Element or ElementArray
            An element, or an array when the components have leading batch
            axes, which broadcast.
        """

        self._require_split("from_components()")
        field = self._field
        group, signed = self._components(kappa, epsilon)
        plus = field.halve(field.add(group, signed))
        minus = field.halve(field.subtract(group, signed))
        coefficients = _kernel._join(self, plus, minus)
        if coefficients.shape == self.coefficient_shape:
            return self._element("loop", coefficients)
        return self._wrap_array(coefficients)

    def lift_group(self, kappa: Any) -> Any:
        """Return the element with group component *kappa* and signed component 0.

        The map is an injective homomorphism of nonunital algebras from the
        group algebra of the quotient group, with dyadic convolution as its
        product, onto an ideal of the loop algebra.
        """

        self._require_split("lift_group()")
        group = self._field.coerce(kappa)
        return self.from_components(group, np.zeros(group.shape, dtype=group.dtype))

    def lift_signed(self, epsilon: Any) -> Any:
        """Return the element with signed component *epsilon* and group component 0.

        The map is an injective homomorphism of nonunital algebras onto an
        ideal of the loop algebra: from the Cayley--Dickson algebra for a
        Cayley--Dickson loop, and from the tensor product of the factors'
        Cayley--Dickson algebras for a central product.
        """

        self._require_split("lift_signed()")
        signed = self._signed_coefficients(epsilon)
        return self.from_components(np.zeros(signed.shape, dtype=signed.dtype), signed)

    def split_array(self, spectral: Any, signed: Any) -> SplitArray:
        """Return a :class:`SplitArray` with the given parts, which are copied.

        *spectral* holds the Walsh--Hadamard transforms of the group
        components and *signed* the signed components, as described for
        :meth:`from_components`. Over a finite field integers are reduced
        modulo the characteristic, also those of a pyfastcd object. Leading
        batch axes broadcast.
        """

        self._require_split("split_array()")
        group, values = self._components(spectral, signed)
        return SplitArray._make(self, group, values)

    def random(
        self, rng: Any = None, *, batch_shape: Any = None, secure: bool = False
    ) -> Any:
        """Return a random element, or an array of them.

        Parameters
        ----------
        rng : numpy.random.Generator or seed, optional
            The source of randomness, passed to ``numpy.random.default_rng``.
        batch_shape : tuple[int, ...], optional
            With a batch shape the result is an :class:`ElementArray`.
        secure : bool, optional
            Draw finite-field coefficients from the operating system's
            cryptographic source through :mod:`secrets`, ignoring *rng*.

        Returns
        -------
        Element or ElementArray
            Over R the coefficients are independent standard normal values,
            over C their real and imaginary parts are, and over a finite
            field the residues are independent and uniform.

        Raises
        ------
        ValueError
            If *secure* is requested over R or C.
        """

        field = self._field
        lead: tuple[int, ...] = ()
        if batch_shape is not None:
            lengths = (
                batch_shape
                if isinstance(batch_shape, (tuple, list))
                else (batch_shape,)
            )
            lead = tuple(_index(length, "a batch length") for length in lengths)
        shape = lead + self.coefficient_shape
        values: np.ndarray
        if secure:
            if not field.exact:
                raise ValueError("secure=True requires a finite coefficient field")
            count = int(np.prod(shape))
            draws = [secrets.randbelow(field.char) for _ in range(count)]
            values = np.array(draws, dtype=np.uint32).reshape(shape)
        else:
            generator = np.random.default_rng(rng)
            if field.exact:
                values = generator.integers(0, field.char, size=shape, dtype=np.uint32)
            elif field.kind == "complex":
                real = generator.standard_normal(shape)
                values = real + 1j * generator.standard_normal(shape)
            else:
                values = generator.standard_normal(shape)
        if batch_shape is None:
            return self._element("loop", values)
        return self._wrap_array(values)

    def _width(self) -> int:
        """Return the number of bytes that encode one residue or real number."""

        if not self._field.exact:
            return 8
        return max(1, ((self.char - 1).bit_length() + 7) // 8)

    def _encode(self, coefficients: np.ndarray) -> bytes:
        """Encode loop-basis coefficients canonically."""

        if self._field.kind == "real":
            return coefficients.astype("<f8").tobytes()
        if self._field.kind == "complex":
            return coefficients.astype("<c16").tobytes()
        words = coefficients.astype(">u4").tobytes()
        octets = np.frombuffer(words, dtype=np.uint8).reshape(-1, 4)
        return octets[:, 4 - self._width() :].tobytes()

    def from_bytes(self, data: Any) -> Element:
        """Return the element encoded by :meth:`Element.to_bytes`.

        *data* is a bytes-like object. Raises ``TypeError`` for anything
        else, and ``ValueError`` if the length is wrong or, over a finite
        field, a residue is not below the characteristic.
        """

        # bytes() would read an integer as a length and a list as octets
        try:
            raw = memoryview(data).tobytes()
        except TypeError:
            raise TypeError("data must be a bytes-like object") from None
        count = int(np.prod(self.coefficient_shape))
        if self._field.kind == "real":
            expected, kind = 8 * count, "<f8"
        elif self._field.kind == "complex":
            expected, kind = 16 * count, "<c16"
        else:
            expected, kind = self._width() * count, ""
        if len(raw) != expected:
            raise ValueError(f"expected {expected} bytes, not {len(raw)}")
        if kind:
            values = np.frombuffer(raw, dtype=kind).astype(self.dtype)
        else:
            octets = np.zeros((count, 4), dtype=np.uint8)
            width = self._width()
            octets[:, 4 - width :] = np.frombuffer(raw, dtype=np.uint8).reshape(
                -1, width
            )
            values = np.frombuffer(octets.tobytes(), dtype=">u4").astype(np.uint32)
            if values.size and int(values.max()) >= self.char:
                raise ValueError("a residue is not below the characteristic")
        return self._element("loop", values.reshape(self.coefficient_shape).copy())

    def array(self, values: Any) -> ElementArray:
        """Copy coefficients into a new :class:`ElementArray`.

        *values* is an element, an array of the algebra, or coefficients of
        shape ``batch_shape + coefficient_shape``. Over a finite field,
        integers are reduced modulo the characteristic.
        """

        if isinstance(values, SplitArray):
            raise TypeError(MIXED_BASIS_MESSAGE)
        if isinstance(values, (Element, ElementArray)):
            return self._wrap_array(np.array(self._own(values)._data("loop")))
        return self._wrap_array(self._field.coerce(values))

    def asarray(self, values: Any, *, copy: Any = None) -> ElementArray:
        """Return an :class:`ElementArray`, sharing storage when possible.

        Storage is shared when *values* is an array of the algebra, or an
        ndarray with the algebra's dtype that, over a finite field, holds
        residues below the characteristic.

        Parameters
        ----------
        values
            As for :meth:`array`.
        copy : bool, optional
            ``None`` shares when possible and copies otherwise, ``True``
            always copies, and ``False`` requires sharing and raises
            ``ValueError`` when it is impossible.
        """

        if copy is not None and not isinstance(copy, bool):
            raise TypeError("copy must be a bool or None")
        if copy is True:
            return self.array(values)
        if isinstance(values, SplitArray):
            raise TypeError(MIXED_BASIS_MESSAGE)
        if isinstance(values, ElementArray):
            return self._own(values)
        shareable = isinstance(values, np.ndarray) and values.dtype == self.dtype
        if shareable and self._field.exact and values.size:
            shareable = int(values.max()) < self.char
        if shareable:
            return self._wrap_array(values, shared=True)
        if copy is False:
            raise ValueError("the values cannot be shared without a copy")
        return self.array(values)

    # Products

    def _signed_algorithm(self, name: Any) -> str:
        """Validate the name of a signed-component method."""

        return _choice(name, "signed_algorithm", self.signed_algorithms)

    def _loop_multiply(
        self, a: np.ndarray, b: np.ndarray, signed_algorithm: str = "auto"
    ) -> np.ndarray:
        """Multiply loop-basis coefficients in the loop basis.

        In characteristic 2 this is the product by the default algorithm;
        elsewhere it is the table product.
        """

        if not self._field.binary:
            return _kernel.table_multiply(self, a, b)
        if self._binary_choice(self._products(a, b)) == "table":
            return _kernel.table_multiply(self, a, b)
        return self._lift.product(("loop", a), ("loop", b), signed_algorithm)

    def _products(self, a: np.ndarray, b: np.ndarray) -> int:
        """Return the number of products of two broadcast coefficient arrays."""

        lead = len(self.coefficient_shape)
        first, second = a.shape[: a.ndim - lead], b.shape[: b.ndim - lead]
        try:
            shape = np.broadcast_shapes(first, second)
        except ValueError:
            # The product itself reports batch shapes that do not broadcast
            return 1
        return int(np.prod(shape))

    def _binary_multiply(
        self, operands: tuple[Any, ...], algorithm: str, signed_algorithm: str = "auto"
    ) -> np.ndarray:
        """Multiply two elements or arrays in characteristic 2.

        Elements contribute the transformed lifts they keep, so a lifted
        product of elements repeats no transform of its operands.
        """

        name = algorithm
        left, right = operands
        if name == "auto":
            count = self._products(left._data("loop"), right._data("loop"))
            name = self._binary_choice(count)
        if name == "table":
            return _kernel.table_multiply(self, left._data("loop"), right._data("loop"))
        pairs = [
            ("lift", operand._data("lift"))
            if isinstance(operand, Element)
            else ("loop", operand._data("loop"))
            for operand in operands
        ]
        return self._lift.product(pairs[0], pairs[1], signed_algorithm)

    def multiply(
        self,
        x: Any,
        y: Any,
        *,
        out: Any = None,
        algorithm: str = "auto",
        signed_algorithm: str = "auto",
    ) -> Any:
        """Return the ordered product ``x y``, broadcasting batch axes.

        Parameters
        ----------
        x, y
            Elements or arrays of the algebra. One operand may be a field
            scalar, which scales the other.
        out : numpy.ndarray or ElementArray, optional
            Storage for a loop-basis result. It must have exactly the
            result's shape and the algebra's dtype.
        algorithm : str, optional
            One of :attr:`algorithms`. ``"split"`` multiplies through the
            decomposition of the algebra: three Walsh--Hadamard transforms,
            one coordinatewise product and one product of signed components,
            or only the two products for operands already in split form.
            ``"table"`` evaluates the definition directly with ``O(D^2)``
            multiplications, in the loop basis. ``"auto"`` selects
            ``"split"``. In characteristic 2, where the algebra has no
            decomposition, ``"lift"`` takes the place of ``"split"``: it
            multiplies the operands with coefficients read as integers over
            a large prime field, or over an extension of it when the
            coefficient field is not F_2, by the split algorithm there, and
            reduces the result. ``"auto"`` then selects ``"lift"`` or ``"table"``
            from the size of the loop and the number of products, between
            :attr:`default_algorithm` for one product and
            :attr:`default_batch_algorithm` for a large batch.
        signed_algorithm : str, optional
            The method for the product of signed components under
            ``"split"`` and ``"lift"``, one of :attr:`signed_algorithms`.
            For a Cayley--Dickson loop the name is passed to pyfastcd
            (``"direct"``, ``"quasilinear"`` and, over R for a quotient
            order up to 1024, ``"cariow_cariowa"``). For a central product it is
            ``"rows"``, ``"schedule"`` or, where it applies, ``"native"``.

        Returns
        -------
        Element, ElementArray or SplitArray
            An :class:`Element` when no operand is an array, otherwise an
            array of the operands' kind. With *out*, the result is *out*
            itself when it is an :class:`ElementArray` and a new array
            around it when it is an ndarray.

        Raises
        ------
        TypeError
            If an :class:`ElementArray` meets a :class:`SplitArray`, if
            ``"table"`` or *out* is used with split arrays, for unsupported
            operands, for an algorithm name that is not a string, or for
            an *out* of the wrong dtype.
        ValueError
            For an unknown algorithm name, operands of different algebras,
            or an *out* of the wrong shape or that is not writable.
        """

        name = _choice(algorithm, "algorithm", self.algorithms)
        if name == "auto" and not self._field.binary:
            name = self.default_algorithm
        method = self._signed_algorithm(signed_algorithm)
        field = self._field
        if field.is_scalar(x) or field.is_scalar(y):
            if field.is_scalar(x) and field.is_scalar(y):
                raise TypeError("at least one operand must belong to the algebra")
            other = self._own(y, "y") if field.is_scalar(x) else self._own(x, "x")
            if name == "table" and isinstance(other, SplitArray):
                raise TypeError("the table algorithm works in the loop basis")
            result = x * other if field.is_scalar(x) else other * y
        else:
            left, right = self._own(x, "x"), self._own(y, "y")
            receiver = left if not isinstance(left, Element) else right
            if not receiver._accepts(left) or not receiver._accepts(right):
                raise TypeError("unsupported operands for multiply")
            if name == "split":
                result = receiver._run(
                    _kernel.multiply, (left, right), signed_algorithm=method
                )
            elif field.binary:
                data = self._binary_multiply((left, right), name, method)
                result = receiver._result("loop", data)
            else:
                if isinstance(receiver, SplitArray):
                    raise TypeError("the table algorithm works in the loop basis")
                data = _kernel.table_multiply(
                    self, left._data("loop"), right._data("loop")
                )
                result = receiver._result("loop", data)
        if out is None:
            return result
        return self._store(result, out)

    def _store(self, result: Any, out: Any) -> ElementArray:
        """Copy a loop-basis result into caller-provided storage."""

        if isinstance(result, SplitArray) or isinstance(out, SplitArray):
            raise TypeError("out= holds a loop-basis result")
        target = out._values if isinstance(out, ElementArray) else out
        if isinstance(out, ElementArray) and out._algebra is not self:
            raise ValueError(DIFFERENT_ALGEBRA_MESSAGE)
        if not isinstance(target, np.ndarray):
            raise TypeError("out must be an ndarray or an ElementArray")
        values = result._data("loop")
        if target.dtype != self.dtype:
            raise TypeError(f"out must have dtype {self.dtype}")
        if target.shape != values.shape:
            raise ValueError(f"out must have shape {values.shape}, not {target.shape}")
        if not target.flags.writeable:
            raise ValueError("out must be writable")
        target[...] = values
        if isinstance(out, ElementArray):
            return out
        return self._wrap_array(target, shared=True)

    def _operator(self, implementation: Any, a: Any, b: Any, x: Any) -> Any:
        """Evaluate an operator commutator on three operands of one kind."""

        operands = (self._own(a, "a"), self._own(b, "b"), self._own(x, "x"))
        arrays = [value for value in operands if not isinstance(value, Element)]
        receiver = arrays[0] if arrays else operands[0]
        for value in operands:
            if not receiver._accepts(value):
                raise TypeError("unsupported operands")
        return receiver._run(implementation, operands)

    def left_operator_commutator(self, a: Any, b: Any, x: Any) -> Any:
        """Return ``a (b x) - b (a x)``."""

        return self._operator(_kernel.left_operator_commutator, a, b, x)

    def right_operator_commutator(self, a: Any, b: Any, x: Any) -> Any:
        """Return ``(x b) a - (x a) b``."""

        return self._operator(_kernel.right_operator_commutator, a, b, x)

    # Idempotents and centre

    def central_idempotents(self) -> tuple[Element, Element]:
        """Return the idempotents ``(1 + [-1]) / 2`` and ``(1 - [-1]) / 2``.

        They are central and orthogonal and sum to the identity.
        Multiplying by the first projects onto the group component, and by
        the second onto the signed component.
        """

        self._require_split("central_idempotents()")
        field = self._field
        half = field.halve(field.scalar(1))
        plus = field.zeros((2, self._size))
        plus[0, 0] = half
        plus[1, 0] = half
        minus = plus.copy()
        minus[1, 0] = field.negate(half)
        return self._element("loop", plus), self._element("loop", minus)

    def primitive_idempotent(self, a: Any) -> Element:
        """Return the idempotent of the character with index *a*.

        The element is ``sum over t of (-1)**popcount(a & t) ([e_t] + [-e_t])``
        divided by ``2 D``. Its spectrum is 1 at coordinate *a* and 0
        elsewhere, and its signed component is zero.
        """

        self._require_split("primitive_idempotent()")
        index = _basis_index(a, self._size, "a")
        spectral = self._field.zeros((self._size,))
        spectral[index] = self._field.scalar(1)
        signed = self._field.zeros((self._size,))
        return self._element("loop", _kernel.from_split(self, (spectral, signed)))

    def _unit_batch(self) -> np.ndarray:
        """Return the identity matrix as a batch of ``D`` coordinate vectors."""

        return _structure._identity(self)

    def primitive_idempotents(self) -> ElementArray:
        """Return all primitive idempotents of the group component.

        Record ``a`` of the result is :meth:`primitive_idempotent` of ``a``.
        The records are orthogonal idempotents that sum to
        ``(1 + [-1]) / 2``.
        """

        self._require_split("primitive_idempotents()")
        units = self._unit_batch()
        zeros = self._field.zeros((self._size, self._size))
        return self._wrap_array(_kernel.from_split(self, (units, zeros)))

    def center_basis(self) -> ElementArray:
        """Return a basis of the center of the algebra.

        The center consists of the elements that commute and associate with
        every element. Where 2 is invertible the basis is the primitive
        idempotents, followed by ``([e_t] - [-e_t]) / 2`` for the central
        loop elements ``e_t``. In characteristic 2 it is ``[e_t]`` for the
        central loop elements, then ``[-e_t]`` for the same elements, then
        ``[e_t] + [-e_t]`` for the others.
        """

        units = self._unit_batch()
        zeros = self._field.zeros((self._size, self._size))
        if self._field.binary:
            return self._wrap_array(_structure.binary_center_basis(self))
        central = units[np.flatnonzero(self._central)]
        spectral = np.concatenate([units, zeros[: central.shape[0]]])
        signed = np.concatenate([zeros, central])
        return self._wrap_array(_kernel.from_split(self, (spectral, signed)))

    # Maps

    def _loop_basis(self, x: Any) -> Any:
        """Check that an operand is an element or a loop-basis array."""

        value = self._own(x, "x")
        if isinstance(value, SplitArray):
            raise TypeError("the operand must be an element or an ElementArray")
        return value

    def apply_automorphism(self, f: Any, x: Any) -> Any:
        """Return the image of *x* under the linear extension of a loop map.

        *f* is a loop automorphism given as a callable on loop elements or
        as an array of positions (see :meth:`CDLoop.is_automorphism`). The
        coefficient of ``[y]`` moves to ``[f(y)]``. The map must be a
        bijection of the loop; that it preserves products is not checked.
        """

        value = self._loop_basis(x)
        permutation = self.loop._permutation(f)
        if np.unique(permutation).size != self.dimension:
            raise ValueError("the map is not a bijection of the loop")
        data = value._data("loop")
        tail = self._field.tail
        lead = data.shape[: data.ndim - tail - 2]
        flat = data.reshape(lead + (self.dimension,) + self._field.shape)
        moved = np.empty(flat.shape, dtype=flat.dtype)
        moved[(Ellipsis, permutation) + (slice(None),) * tail] = flat
        return value._result("loop", moved.reshape(data.shape))

    def character_automorphism(self, a: Any, x: Any) -> Any:
        """Return the image of *x* under ``e_t -> (-1)**popcount(a & t) e_t``.

        The map exchanges the coefficients of ``[e_t]`` and ``[-e_t]`` for
        every index ``t`` with ``popcount(a & t)`` odd. It is an algebra
        automorphism for each of the ``D`` indices ``a``.
        """

        return self.apply_automorphism(self.loop.character_automorphism(a), x)

    def _source(self, x: Any, loop: Any) -> Any:
        """Check an operand from the loop algebra of *loop* over the same field."""

        if not isinstance(x, (Element, ElementArray)):
            raise TypeError("the operand must be an element or an ElementArray")
        if x._algebra is not LoopAlgebra(loop, **self._field.selectors):
            raise ValueError(
                f"the operand must belong to the loop algebra of {loop!r} "
                "over the same coefficient field"
            )
        return x

    def _place(self, x: Any, indices: np.ndarray) -> Any:
        """Copy the coefficients of *x* to the given indices of a new element."""

        data = x._data("loop")
        tail = self._field.tail
        lead = data.shape[: data.ndim - tail - 2]
        values = self._field.zeros(lead + (2, self._size))
        values[(Ellipsis, indices) + (slice(None),) * tail] = data
        if isinstance(x, Element):
            return self._element("loop", values)
        return self._wrap_array(values)

    def embed(self, x: Any) -> Any:
        """Return the image of an element of the loop algebra of a smaller ``Q_k``.

        Defined for a Cayley--Dickson loop ``Q_n``. ``Q_k`` with ``k <= n``
        is the subloop on the indices below ``2**k``, and the embedding of
        loop algebras keeps every coefficient at its index.
        """

        if not isinstance(self.loop, CDLoop):
            raise TypeError("embed() is defined for a Cayley--Dickson loop")
        if not isinstance(x, (Element, ElementArray)):
            raise TypeError("the operand must be an element or an ElementArray")
        source = x._algebra.loop
        if not isinstance(source, CDLoop) or source.level > self.loop.level:
            raise ValueError(
                "the operand must come from a smaller Cayley--Dickson loop"
            )
        value = self._source(x, source)
        return self._place(value, np.arange(source.quotient_order))

    def factor_embedding(self, i: Any, x: Any) -> Any:
        """Return the image of an element of the loop algebra of factor *i*.

        Defined for a central product. The basis element ``[s e_p]`` of the
        loop algebra of ``Q_ni`` maps to the basis element with the same
        sign, index ``p`` in factor *i* and index 0 in every other factor.
        The map is an injective homomorphism of unital algebras.
        """

        if not isinstance(self.loop, CentralProduct):
            raise TypeError("factor_embedding() is defined for a central product")
        position = _basis_index(i, len(self.loop.levels), "the factor number")
        source = CDLoop(self.loop.levels[position])
        value = self._source(x, source)
        shift = self.loop._shifts[position]
        return self._place(value, np.arange(source.quotient_order) << shift)

    # Linear algebra

    def _matrix(self, x: Any, side: str, basis: Any) -> np.ndarray:
        """Return a multiplication matrix of one element."""

        if not isinstance(x, Element):
            raise TypeError("a multiplication matrix is defined for one element")
        value = self._own(x, "x")
        name = _choice(basis, "basis", ("loop", "split"))
        if self._field.binary:
            if name == "split":
                self._require_split("a matrix in split coordinates")
            return _structure.loop_matrix(self, value._data("loop"), side)
        return _structure.left_matrix(self, value._data("split"), side, name)

    def left_matrix(self, x: Any, *, basis: str = "loop") -> np.ndarray:
        """Return the matrix of ``y -> x y``.

        With ``basis="loop"`` the matrix ``M`` satisfies
        ``(x * y).coefficients.ravel() == M @ y.coefficients.ravel()`` up to
        rounding over R and C. Over a prime field its entries are ``uint32``
        residues, and the identity holds when the right side is computed in
        integers that do not overflow and reduced modulo the
        characteristic. Over an extension field it has a trailing
        polynomial axis and its entries are field elements. With
        ``basis="split"`` the matrix acts on the spectral coordinates
        followed by the signed coordinates and is block diagonal; that
        basis is not defined in characteristic 2.
        """

        return self._matrix(x, "left", basis)

    def right_matrix(self, x: Any, *, basis: str = "loop") -> np.ndarray:
        """Return the matrix of ``y -> y x``, in the layout of :meth:`left_matrix`."""

        return self._matrix(x, "right", basis)

    def structure_constants(self) -> np.ndarray:
        """Return the structure constants as an ``int8`` array.

        Entry ``[i, j, k]`` is 1 when the product of the basis elements at
        positions ``i`` and ``j`` is the basis element at position ``k``,
        and 0 otherwise. The array has ``dimension**3`` entries, so it is
        built only for dimensions up to 256; :meth:`CDLoop.cayley_table`
        holds the same information for larger loops.
        """

        if self.dimension > _CONSTANTS_LIMIT:
            raise ValueError("the algebra is too large for dense structure constants")
        table = self.loop.cayley_table()
        constants = np.zeros((self.dimension,) * 3, dtype=np.int8)
        rows, columns = np.indices(table.shape)
        constants[rows, columns, table] = 1
        return constants

    def subalgebra_generated_by(self, x: Any) -> GeneratedSubalgebra:
        """Describe the unital subalgebra generated by one element.

        Defined for the loop algebra of a Cayley--Dickson loop, and for
        every loop in characteristic 2; see :class:`GeneratedSubalgebra`.
        """

        if not isinstance(x, Element):
            raise TypeError("the operand must be one element")
        value = self._own(x, "x")
        polynomial = value.minimal_polynomial()
        if self._field.binary:
            return GeneratedSubalgebra(
                dimension=polynomial.shape[0] - 1,
                minimal_polynomial=polynomial,
                spectral_values=None,
                signed_polynomial=None,
            )
        spectral, signed = value._data("split")
        return GeneratedSubalgebra(
            dimension=polynomial.shape[0] - 1,
            minimal_polynomial=polynomial,
            spectral_values=_structure.distinct_values(self._field, spectral),
            signed_polynomial=_structure.signed_polynomial(self, signed),
        )


def _rebuild_algebra(loop: Any, char: int, deg: int, field: Any) -> LoopAlgebra:
    """Recreate a pickled algebra."""

    if field is not None:
        return LoopAlgebra(loop, field=field)
    return LoopAlgebra(loop, char=char, deg=deg)
