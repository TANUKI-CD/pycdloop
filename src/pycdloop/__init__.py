"""Arithmetic in Cayley--Dickson loops, their central products, and loop algebras.

``pycdloop`` models the Cayley--Dickson loop ``Q_n`` of signed basis elements
of the Cayley--Dickson algebra of dimension ``2**n``, central products of such
loops, and the loop algebras of both over the real numbers, the complex
numbers, and finite fields. Where 2 is invertible, products in a loop algebra
are evaluated through its decomposition into a group algebra and a
Cayley--Dickson algebra, or for a central product a tensor product of
Cayley--Dickson algebras, with the Cayley--Dickson arithmetic delegated to
:mod:`pyfastcd`. In characteristic 2, where there is no such decomposition,
they are evaluated from the multiplication table, or by lifting to a field
in which there is one.

The conventional abbreviation is ``cdl``::

    import pycdloop as cdl

    Q = cdl.CDLoop(3)
    A = cdl.LoopAlgebra(Q)
    x = A.basis(Q.basis(1)) + 2 * A.basis(-Q.basis(4))
    y = x * x

Public API
----------
CDLoop, CentralProduct
    Immutable, cached loops.
LoopElement
    One signed basis element of a loop.
LoopAlgebra
    Immutable, cached parent of elements and arrays, and their constructor.
BinaryField, BinaryFieldElement
    The finite fields of characteristic 2 and their scalars; pyfastcd
    provides the fields of odd characteristic.
Element
    One immutable element of a loop algebra.
ElementArray
    A NumPy-backed batch of elements stored by loop-basis coefficients.
SplitArray
    A batch stored in the coordinates in which products need no transform.
GeneratedSubalgebra
    The description of the subalgebra generated by one element.
wht, dyadic_convolve
    The Walsh--Hadamard transform and the product of the group component.
linalg, codes, testing
    Rank and null spaces over the coefficient fields, tools for codes in
    loop algebras, and identity checks.

Notes
-----
Basis elements and signs follow the conventions of pyfastcd. The basis element
``[-e_t]`` of a loop algebra is distinct from ``-[e_t]``.
"""

